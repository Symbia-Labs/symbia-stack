/**
 * Emit file-reader.wasm from hand-encoded bytes — the exact binary encoding of
 * file-reader.wat. Zero toolchain, same rule as the add spike.
 *
 * Sections: header | type | import | func | export | code
 *   type   : two signatures — read_byte (i32,i32)->i32 and checksum4 (i32)->i32
 *   import : host.read_byte  (this is the capability the module demands)
 *   export : checksum4       (func index 1 — the import is func index 0)
 */
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const bytes = Uint8Array.from([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
  // type section: (i32,i32)->i32 ; (i32)->i32
  0x01, 0x0c, 0x02, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f, 0x60, 0x01, 0x7f, 0x01, 0x7f,
  // import section: "host"."read_byte" func type 0
  0x02, 0x12, 0x01, 0x04, 0x68, 0x6f, 0x73, 0x74, 0x09, 0x72, 0x65, 0x61, 0x64, 0x5f, 0x62, 0x79, 0x74, 0x65, 0x00, 0x00,
  // func section: one func, type 1
  0x03, 0x02, 0x01, 0x01,
  // export section: "checksum4" -> func 1
  0x07, 0x0d, 0x01, 0x09, 0x63, 0x68, 0x65, 0x63, 0x6b, 0x73, 0x75, 0x6d, 0x34, 0x00, 0x01,
  // code section
  0x0a, 0x23, 0x01, 0x21, 0x00,
  0x20, 0x00, 0x41, 0x00, 0x10, 0x00,       // read(slot,0)
  0x20, 0x00, 0x41, 0x01, 0x10, 0x00, 0x6a, // + read(slot,1)
  0x20, 0x00, 0x41, 0x02, 0x10, 0x00, 0x6a, // + read(slot,2)
  0x20, 0x00, 0x41, 0x03, 0x10, 0x00, 0x6a, // + read(slot,3)
  0x41, 0xff, 0x01, 0x71,                   // & 255
  0x0b,                                     // end
]);

writeFileSync(new URL('./file-reader.wasm', import.meta.url), bytes);
console.log(`wrote file-reader.wasm (${bytes.length} bytes)`);
console.log(`sha256: ${createHash('sha256').update(bytes).digest('hex')}`);
